"""
Сборка мета‑промпта для ветки explain из explain_spec.json.

Этот модуль не вызывает API: формирует готовый промпт по шаблону
для вставки в браузерный ИИ.
"""

from __future__ import annotations

from typing import Any


def _v(spec: dict[str, Any], key: str, fallback: str) -> str:
    val = spec.get(key)
    if val is None:
        return fallback
    t = str(val).strip()
    return t if t else fallback


def build_explain_browser_prompt(spec: dict[str, Any]) -> str:
    topic = _v(spec, "topic", "не указана")
    goal = _v(spec, "goal", "понять тему на практическом уровне")
    audience = _v(spec, "audience", "сам пользователь")
    depth = _v(spec, "depth", "базово, с примерами")
    fmt = _v(spec, "format", "пошаговый разбор")
    style = _v(spec, "style", "простой и понятный")
    no_no = _v(spec, "no_no", "нет")

    return (
        "Ты — опытный преподаватель и технический эксперт.\n"
        "Твоя задача — понятно объяснить тему пользователю.\n\n"
        "Спецификация:\n\n"
        f"Тема: {topic}\n"
        f"Цель объяснения: {goal}\n"
        f"Кто спрашивает: {audience}\n"
        f"Глубина: {depth}\n"
        f"Формат: {fmt}\n"
        f"Стиль: {style}\n"
        f"Особые пожелания: {no_no}\n\n"
        "Жёсткие правила:\n"
        "1. Исходи из того, что объяснение нужно именно этому пользователю (а не широкой аудитории).\n"
        "2. Структурируй объяснение логично: ввод в тему, основная часть, примеры, вывод.\n"
        "3. Если указано \"подробно\" или аналог — объясняй пошагово, от простого к сложному.\n"
        "4. Используй понятный язык, избегай лишнего жаргона, если не указано обратное.\n"
        "5. Если в спецификации есть ограничения (поле no_no), строго их соблюдай.\n"
        "6. Не добавляй в ответ никаких инструкций по использованию ИИ — только само объяснение.\n\n"
        "Сначала подумай, как лучше выстроить объяснение для этой аудитории, "
        "затем сразу выдай готовый текст без дополнительных комментариев."
    )
